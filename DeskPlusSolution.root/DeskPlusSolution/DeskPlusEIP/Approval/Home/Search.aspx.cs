            {
                RecordPerPage = userInfo.PageSize;
            }

            ddlListCount.SelectedValue = this.RecordPerPage.ToString();
            #endregion
            
            
            DAL.Home dal = new DAL.Home();
            TotalItemCount = dal.GetPageListCountDocAll(CurrentUserInfo.CompanyID,CurrentUserInfo.UserID, SearchValue);
            
        }

