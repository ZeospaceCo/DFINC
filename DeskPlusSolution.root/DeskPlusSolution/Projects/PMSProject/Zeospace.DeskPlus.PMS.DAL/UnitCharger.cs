        /// <summary>
        /// Gets the unit charger list.
        /// </summary>
        /// <param name="reader">The reader.</param>
        /// <returns></returns>
        protected List<UnitChargerInfo> GetUnitChargerList(IDataReader reader)
        {
            List<UnitChargerInfo> list = new List<UnitChargerInfo>();
            while (reader.Read())
                list.Add(GetUnitCharger(reader));
            return list;
        }

